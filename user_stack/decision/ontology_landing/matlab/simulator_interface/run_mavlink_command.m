function ok = run_mavlink_command(action, x, y, z, timeout_s, sim, cfg)
%RUN_MAVLINK_COMMAND Best-effort MAVLink helper modeled after integrated_main.m.

ok = false;
if nargin < 7
    cfg = landing_decision_config();
end

if nargin < 6 || isempty(sim)
    ns = cfg.simulator.namespace;
else
    ns = cfg.simulator.namespace;
    if isfield(sim, 'namespace') && ~isempty(sim.namespace)
        ns = sim.namespace;
    end
end

py_file = [tempname, '.py'];
fid = fopen(py_file, 'w');
if fid < 0
    return;
end
cleaner = onCleanup(@() delete_temp_file(py_file)); %#ok<NASGU>

script = sprintf([ ...
    'import sys,time\n' ...
    'from pymavlink import mavutil\n' ...
    'action = sys.argv[1]\n' ...
    'value = sys.argv[2:]\n' ...
    'm = None\n' ...
    'last_err = ""\n' ...
    'uris = ("udpin:127.0.0.1:14550", "udpin:127.0.0.1:14551", "tcp:127.0.0.1:5760")\n' ...
    'for uri in uris:\n' ...
    '    try:\n' ...
    '        m = mavutil.mavlink_connection(uri, source_system=251, timeout=2)\n' ...
    '        heartbeat = m.wait_heartbeat(timeout=4)\n' ...
    '        if heartbeat is None:\n' ...
    '            raise RuntimeError("heartbeat timeout")\n' ...
    '        print(f"[MAVLINK] connected uri={uri} target={m.target_system}:{m.target_component} mode={m.flightmode}")\n' ...
    '        break\n' ...
    '    except Exception as e:\n' ...
    '        last_err = f"{uri}: {e}"\n' ...
    '        m = None\n' ...
    'if m is None:\n' ...
    '    raise RuntimeError(f"no mavlink connection ({last_err})")\n' ...
    'def hb():\n' ...
    '    m.mav.heartbeat_send(mavutil.mavlink.MAV_TYPE_GCS, mavutil.mavlink.MAV_AUTOPILOT_INVALID, 0, 0, mavutil.mavlink.MAV_STATE_ACTIVE, 3)\n' ...
    'def set_param(name, value, ptype=mavutil.mavlink.MAV_PARAM_TYPE_REAL32):\n' ...
    '    m.mav.param_set_send(m.target_system, m.target_component, name.encode("ascii"), float(value), ptype)\n' ...
    '    deadline = time.time() + 2\n' ...
    '    while time.time() < deadline:\n' ...
    '        msg = m.recv_match(type="PARAM_VALUE", blocking=True, timeout=0.2)\n' ...
    '        if msg is not None and msg.param_id.strip("\\x00") == name:\n' ...
    '            return True\n' ...
    '    return False\n' ...
    'def wait_mode(mode, timeout=8):\n' ...
    '    deadline = time.time() + timeout\n' ...
    '    while time.time() < deadline:\n' ...
    '        hb(); m.recv_match(type="HEARTBEAT", blocking=True, timeout=0.5)\n' ...
    '        if str(m.flightmode).upper() == mode.upper():\n' ...
    '            return True\n' ...
    '    return False\n' ...
    'def wait_armed(timeout=8):\n' ...
    '    deadline = time.time() + timeout\n' ...
    '    while time.time() < deadline:\n' ...
    '        hb(); msg = m.recv_match(type="HEARTBEAT", blocking=True, timeout=0.5)\n' ...
    '        if msg is not None and (msg.base_mode & mavutil.mavlink.MAV_MODE_FLAG_SAFETY_ARMED):\n' ...
    '            return True\n' ...
    '    return False\n' ...
    'def wait_disarmed(timeout=8):\n' ...
    '    deadline = time.time() + timeout\n' ...
    '    while time.time() < deadline:\n' ...
    '        hb(); msg = m.recv_match(type="HEARTBEAT", blocking=True, timeout=0.5)\n' ...
    '        if msg is not None and not (msg.base_mode & mavutil.mavlink.MAV_MODE_FLAG_SAFETY_ARMED):\n' ...
    '            return True\n' ...
    '    return False\n' ...
    'def disarm_vehicle(timeout=12, aggressive=False):\n' ...
    '    attempts = 2 if aggressive else 4\n' ...
    '    wait_window = max(1.0, min(3.0, timeout / max(2, attempts)))\n' ...
    '    for attempt in range(attempts):\n' ...
    '        force = 21196 if aggressive or attempt >= max(1, attempts - 2) else 0\n' ...
    '        m.mav.command_long_send(m.target_system, m.target_component, mavutil.mavlink.MAV_CMD_COMPONENT_ARM_DISARM, 0, 0, force,0,0,0,0,0)\n' ...
    '        if wait_disarmed(timeout=wait_window):\n' ...
    '            return True\n' ...
    '        time.sleep(0.5)\n' ...
    '    return False\n' ...
    'if action == "arm_takeoff":\n' ...
    '    alt = float(value[0])\n' ...
    '    set_param("ARMING_CHECK", 0, mavutil.mavlink.MAV_PARAM_TYPE_INT32)\n' ...
    '    time.sleep(2.0)\n' ...
    '    mapping = m.mode_mapping() or {}\n' ...
    '    if "GUIDED" in mapping:\n' ...
    '        m.mav.set_mode_send(m.target_system, mavutil.mavlink.MAV_MODE_FLAG_CUSTOM_MODE_ENABLED, mapping["GUIDED"])\n' ...
    '    else:\n' ...
    '        m.set_mode("GUIDED")\n' ...
    '    wait_mode("GUIDED", timeout=10)\n' ...
    '    armed = False\n' ...
    '    for attempt in range(4):\n' ...
    '        force = 21196 if attempt >= 1 else 0\n' ...
    '        m.mav.command_long_send(m.target_system, m.target_component, mavutil.mavlink.MAV_CMD_COMPONENT_ARM_DISARM, 0, 1, force,0,0,0,0,0)\n' ...
    '        if wait_armed(timeout=5):\n' ...
    '            armed = True; break\n' ...
    '        time.sleep(1.0)\n' ...
    '    if not armed:\n' ...
    '        raise RuntimeError("vehicle did not arm")\n' ...
    '    m.mav.command_long_send(m.target_system, m.target_component, mavutil.mavlink.MAV_CMD_NAV_TAKEOFF, 0, 0,0,0,0,0,0, alt)\n' ...
    '    rose = False\n' ...
    '    takeoff_sent_t = time.time()\n' ...
    '    deadline = time.time() + 30\n' ...
    '    while time.time() < deadline:\n' ...
    '        hb()\n' ...
    '        msg = m.recv_match(type=["GLOBAL_POSITION_INT", "LOCAL_POSITION_NED", "STATUSTEXT"], blocking=True, timeout=1)\n' ...
    '        if msg is None:\n' ...
    '            if time.time() - takeoff_sent_t > 5 and not rose:\n' ...
    '                m.mav.command_long_send(m.target_system, m.target_component, mavutil.mavlink.MAV_CMD_NAV_TAKEOFF, 0, 0,0,0,0,0,0, alt)\n' ...
    '                takeoff_sent_t = time.time()\n' ...
    '            continue\n' ...
    '        if msg.get_type() == "GLOBAL_POSITION_INT":\n' ...
    '            rel_alt_m = float(msg.relative_alt) / 1000.0\n' ...
    '            print(f"TAKEOFF rel_alt={rel_alt_m:.2f}")\n' ...
    '            if rel_alt_m >= max(0.8, alt * 0.08):\n' ...
    '                rose = True; break\n' ...
    '        elif msg.get_type() == "LOCAL_POSITION_NED":\n' ...
    '            z = float(msg.z); print(f"TAKEOFF z={z:.2f}")\n' ...
    '            if z < -0.8:\n' ...
    '                rose = True; break\n' ...
    '    if not rose:\n' ...
    '        raise RuntimeError("takeoff climb not detected")\n' ...
    'elif action == "local_wp":\n' ...
    '    x,y,z = [float(v) for v in value[:3]]\n' ...
    '    type_mask = (mavutil.mavlink.POSITION_TARGET_TYPEMASK_VX_IGNORE | mavutil.mavlink.POSITION_TARGET_TYPEMASK_VY_IGNORE | mavutil.mavlink.POSITION_TARGET_TYPEMASK_AX_IGNORE | mavutil.mavlink.POSITION_TARGET_TYPEMASK_AY_IGNORE | mavutil.mavlink.POSITION_TARGET_TYPEMASK_AZ_IGNORE | mavutil.mavlink.POSITION_TARGET_TYPEMASK_YAW_IGNORE | mavutil.mavlink.POSITION_TARGET_TYPEMASK_YAW_RATE_IGNORE)\n' ...
    '    m.mav.set_position_target_local_ned_send(int(time.time()*1000)&0xffffffff, m.target_system, m.target_component, mavutil.mavlink.MAV_FRAME_LOCAL_NED, type_mask, x, y, -z, 0,0,0.35, 0,0,0, 0,0)\n' ...
    '    time.sleep(0.2)\n' ...
    'elif action == "land":\n' ...
    '    m.set_mode("LAND")\n' ...
    '    time.sleep(3)\n' ...
    'elif action == "disarm":\n' ...
    '    cmd_timeout = max(3.0, min(float(value[3]) if len(value) > 3 else 4.0, 6.0))\n' ...
    '    if not disarm_vehicle(timeout=cmd_timeout, aggressive=True):\n' ...
    '        raise RuntimeError("disarm not confirmed")\n' ...
    'elif action == "land_disarm":\n' ...
    '    try:\n' ...
    '        m.set_mode("LAND")\n' ...
    '        wait_mode("LAND", timeout=6)\n' ...
    '    except Exception:\n' ...
    '        pass\n' ...
    '    landed_count = 0\n' ...
    '    deadline = time.time() + 20\n' ...
    '    while time.time() < deadline:\n' ...
    '        hb()\n' ...
    '        msg = m.recv_match(type=["GLOBAL_POSITION_INT", "LOCAL_POSITION_NED", "HEARTBEAT"], blocking=True, timeout=0.5)\n' ...
    '        if msg is None:\n' ...
    '            continue\n' ...
    '        if msg.get_type() == "GLOBAL_POSITION_INT":\n' ...
    '            if float(msg.relative_alt) / 1000.0 <= 0.45:\n' ...
    '                landed_count += 1\n' ...
    '            else:\n' ...
    '                landed_count = 0\n' ...
    '        elif msg.get_type() == "LOCAL_POSITION_NED":\n' ...
    '            if abs(float(msg.z)) <= 0.45:\n' ...
    '                landed_count += 1\n' ...
    '            else:\n' ...
    '                landed_count = 0\n' ...
    '        if landed_count >= 2:\n' ...
    '            break\n' ...
    '    cmd_timeout = max(4.0, min(float(value[3]) if len(value) > 3 else 6.0, 8.0))\n' ...
    '    if not disarm_vehicle(timeout=cmd_timeout, aggressive=True):\n' ...
    '        raise RuntimeError("land_disarm did not confirm disarmed state")\n' ...
    'else:\n' ...
    '    raise RuntimeError(f"unknown action: {action}")\n' ...
    'print("OK")\n' ...
]);
fprintf(fid, '%s', script);
fclose(fid);

cmd = sprintf('timeout %d python3 "%s" "%s" %s 2>&1', ceil(timeout_s) + 10, py_file, action, shell_quote_values(x, y, z, timeout_s));
[status, out] = system(cmd);
ok = status == 0 && contains(out, 'OK');
if ~ok
    fprintf('[run_mavlink_command] %s failed (status=%d): %s\n', action, status, strtrim(out));
end

end

function s = shell_quote_values(varargin)
s = '';
for k = 1:nargin
    if isnan(varargin{k})
        valueStr = '0';
    else
        valueStr = num2str(varargin{k});
    end
    s = [s, '"', valueStr, '" ']; %#ok<AGROW>
end
end

function delete_temp_file(file_path)
try
    if exist(file_path, 'file')
        delete(file_path);
    end
catch
end
end
