%% Diagnostic test to capture Python MAVLink sequence output

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
cd(repoRoot)
addpath(genpath(fullfile(repoRoot, 'matlab')))

% Create a test Python script that shows what the arm_mode_takeoff_sequence is doing
altitude_m = 1.0;
lat = -35.363262;
lon = 149.165237;

py_file = '/tmp/test_arm_takeoff_debug.py';
fid = fopen(py_file, 'w');

script = sprintf([ ...
    'import sys, time\n' ...
    'from pymavlink import mavutil\n' ...
    '\n' ...
    'print("[SEQUENCE_DEBUG] Connecting to MAVLink (try udp:14550 then tcp:5760)...")\n' ...
    'm = None\n' ...
    'for uri in ("udp:127.0.0.1:14550", "tcp:127.0.0.1:5760"):\n' ...
    '    try:\n' ...
    '        m = mavutil.mavlink_connection(uri, source_system=251)\n' ...
    '        m.wait_heartbeat(timeout=10)\n' ...
    '        print(f"[SEQUENCE_DEBUG] connected via {uri}")\n' ...
    '        break\n' ...
    '    except Exception as e:\n' ...
    '        m = None\n' ...
    'if m is None:\n' ...
    '    print("[SEQUENCE_DEBUG] ERROR: no mavlink connection")\n' ...
    '    sys.exit(1)\n' ...
    '    print(f"[SEQUENCE_DEBUG] Heartbeat received from SYSID={m.target_system}")\n' ...
    'except Exception as e:\n' ...
    '    print(f"[SEQUENCE_DEBUG] ERROR: {e}")\n' ...
    '    sys.exit(1)\n' ...
    '\n' ...
    'def send_heartbeat():\n' ...
    '    m.mav.heartbeat_send(mavutil.mavlink.MAV_TYPE_GCS, mavutil.mavlink.MAV_AUTOPILOT_INVALID, 0, 0, mavutil.mavlink.MAV_STATE_ACTIVE, 3)\n' ...
    '\n' ...
    'print("[SEQUENCE_DEBUG] STEP 1: Arming...")\n' ...
    'for i in range(5):\n' ...
    '    send_heartbeat()\n' ...
    '    time.sleep(0.2)\n' ...
    'time.sleep(1)\n' ...
    'm.arducopter_arm()\n' ...
    'print("[SEQUENCE_DEBUG] Arm command sent")\n' ...
    '\n' ...
    'arm_deadline = time.time() + 15\n' ...
    'armed = False\n' ...
    'while time.time() < arm_deadline:\n' ...
    '    send_heartbeat()\n' ...
    '    msg = m.recv_match(type="HEARTBEAT", blocking=True, timeout=1.0)\n' ...
    '    if msg is not None:\n' ...
    '        is_armed = msg.base_mode & 128\n' ...
    '        if is_armed:\n' ...
    '            print("[SEQUENCE_DEBUG] Vehicle ARMED")\n' ...
    '            armed = True\n' ...
    '            break\n' ...
    '    time.sleep(0.2)\n' ...
    '\n' ...
    'print("[SEQUENCE_DEBUG] STEP 2: Set GUIDED mode...")\n' ...
    'send_heartbeat()\n' ...
    'time.sleep(0.5)\n' ...
    'm.set_mode("GUIDED")\n' ...
    'print("[SEQUENCE_DEBUG] Mode switch command sent")\n' ...
    '\n' ...
    'mode_deadline = time.time() + 10\n' ...
    'guided = False\n' ...
    'while time.time() < mode_deadline:\n' ...
    '    send_heartbeat()\n' ...
    '    msg = m.recv_match(type="HEARTBEAT", blocking=True, timeout=0.5)\n' ...
    '    if msg is not None:\n' ...
    '        flight_mode = m.flightmode\n' ...
    '        if flight_mode and flight_mode.upper() == "GUIDED":\n' ...
    '            print(f"[SEQUENCE_DEBUG] Mode confirmed: GUIDED")\n' ...
    '            guided = True\n' ...
    '            break\n' ...
    '    time.sleep(0.2)\n' ...
    '\n' ...
    'print("[SEQUENCE_DEBUG] STEP 3: Send altitude target...")\n' ...
    'current_lat = %.7f\n' ...
    'current_lon = %.7f\n' ...
    'alt_cmd = %.2f\n' ...
    'print(f"[SEQUENCE_DEBUG] TARGET: LAT={current_lat:.6f} LON={current_lon:.6f} ALT={alt_cmd:.2f}m AGL")\n' ...
    '\n' ...
    '# Send position target\n' ...
    'print("[SEQUENCE_DEBUG] Sending SET_POSITION_TARGET_GLOBAL_INT...")\n' ...
    'm.mav.set_position_target_global_int_send(\n' ...
    '    time_boot_ms=0,\n' ...
    '    target_system=m.target_system,\n' ...
    '    target_component=m.target_component,\n' ...
    '    coordinate_frame=mavutil.mavlink.MAV_FRAME_GLOBAL_RELATIVE_ALT,\n' ...
    '    type_mask=0b0000111111111000,\n' ...
    '    lat_int=int(current_lat * 1e7),\n' ...
    '    lon_int=int(current_lon * 1e7),\n' ...
    '    alt=alt_cmd,\n' ...
    '    vx=0, vy=0, vz=0,\n' ...
    '    afx=0, afy=0, afz=0,\n' ...
    '    yaw=0, yaw_rate=0\n' ...
    ')\n' ...
    'print("[SEQUENCE_DEBUG] Position target sent")\n' ...
    '\n' ...
    'print("[SEQUENCE_DEBUG] Monitoring altitude (10s)...")\n' ...
    't_end = time.time() + 10\n' ...
    'while time.time() < t_end:\n' ...
    '    send_heartbeat()\n' ...
    '    msg = m.recv_match(type=["GLOBAL_POSITION_INT", "LOCAL_POSITION_NED"], blocking=True, timeout=0.5)\n' ...
    '    if msg is not None:\n' ...
    '        if msg.get_type() == "GLOBAL_POSITION_INT":\n' ...
    '            rel_alt = float(msg.relative_alt) / 1000.0\n' ...
    '            print(f"[SEQUENCE_DEBUG] GLOBAL_POSITION: rel_alt={rel_alt:.2f}m")\n' ...
    '        elif msg.get_type() == "LOCAL_POSITION_NED":\n' ...
    '            z = float(msg.z)\n' ...
    '            print(f"[SEQUENCE_DEBUG] LOCAL_POSITION: z={z:.2f}m")\n' ...
    '\n' ...
    'print("[SEQUENCE_DEBUG] Sequence complete")\n' ...
], altitude_m, lat, lon, altitude_m);

fwrite(fid, script, 'char');
fclose(fid);

fprintf('[DEBUG] Running diagnostic takeoff sequence...\n');
cmd = sprintf('python3 "%s" 2>&1', py_file);
[status, out] = system(cmd);

fprintf('\n========== PYTHON OUTPUT ==========\n%s\n====================================\n\n', out);

if status == 0
    fprintf('[DEBUG] Sequence returned success\n');
else
    fprintf('[DEBUG] Sequence returned exit code: %d\n', status);
end

delete(py_file);
